/**
 * Giri Stories — 4-Band Decodable Reading System
 *
 * Band A: Core Decodable Minis     (25–45 words, 4–6 sentences)
 * Band B: Decodable Story Readers  (45–80 words, 6–10 sentences)
 * Band C: Fluency Readers          (80–140 words, paragraph format)
 * Band D: Bridge / Chapter Readers (140–250 words, multi-paragraph)
 *
 * Each band progresses on 5 tracks:
 *   1. Code complexity   (short vowels → long → r-controlled → diphthongs)
 *   2. Text length       (25 → 250 words)
 *   3. Sentence complexity (one clause → full paragraph syntax)
 *   4. Narrative complexity (one event → delayed resolution)
 *   5. Support load      (strong pattern → mostly independent)
 *
 * HFW Tiers:
 *   Tier 1: the, a, and, is, it, to, in, on, my
 *   Tier 2: was, said, we, he, she, they, of, for, with, went
 *   Tier 3: could, would, should, there, where, one, some, were
 *   Band A → Tier 1 only | Band B → 1–2 | Band C → 1–3 | Band D → flexible
 *
 * Sight-word weave: the ten Band A minis (core-a-01…10) are aligned 1:1 to
 * the ten easy sight-word quests. Each story's `sightWords` list is the
 * cumulative set of words its quest (and all earlier quests) have
 * pre-taught, so Story N may use exactly what Quests 1…N introduced. The
 * decodability validator treats those as legal — see getIntroducedSightWords
 * in sightwords.js and the `sight` route in decodability.js.
 */

